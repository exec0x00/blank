"""Merge several session packs into one unit pack (a MODULE per session) so the engine can build a unit master.

usage: python3 -I merge_unit.py <out_pack_dir> --title "…" --unit "…" --slug … --header "…" <session_pack_dir> [...]

Session packs are given in teaching order. Every topic is renumbered (T1… across the unit) and every item id
(E/G/F/W/C<topic>.<n>) is mapped to the new topic number; all references inside strings (topic fields, "W3.1",
"E1.1–E4.2", TOP_FORMULAS, PYQ "worked") are rewritten with an exact-token map, so source tags such as "T008 00:07:38"
are untouched. Figures are re-exported from the original figures.py / figs/*.py under their new ids (figs/sNN.py).
The out pack is generated: re-run this script after any session pack changes, then make.sh on the out pack.
"""
import argparse, glob, importlib.util, json, os, pprint, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
from build import LISTS, load_pack  # noqa: E402

ID_RE = re.compile(r"(?<![\w·])([TEGFWCM])(\d+)(?:\.(\d+))?(?![\w·])")


def remap(obj, idmap):
    if isinstance(obj, str):
        return ID_RE.sub(lambda m: idmap.get(m.group(0), m.group(0)), obj)
    if isinstance(obj, list):
        return [remap(x, idmap) for x in obj]
    if isinstance(obj, tuple):
        return tuple(remap(x, idmap) for x in obj)
    if isinstance(obj, dict):
        return {k: (v if k in ("srcs", "tex", "code") else remap(v, idmap)) for k, v in obj.items()}
    return obj


def fig_modules(pack):
    return [p for p in [os.path.join(pack, "figures.py")] if os.path.exists(p)] + sorted(glob.glob(os.path.join(pack, "figs", "*.py")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out"); ap.add_argument("packs", nargs="+")
    ap.add_argument("--title", required=True); ap.add_argument("--unit", required=True)
    ap.add_argument("--slug", required=True); ap.add_argument("--header", required=True)
    ap.add_argument("--scope", default=None); ap.add_argument("--course", default=None)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    for d in ("parts", "figs"):
        shutil.rmtree(os.path.join(out, d), ignore_errors=True)
        os.makedirs(os.path.join(out, d))
    merged = {k: [] for k in LISTS}
    P = {"sources": [], "gaps": [], "asr_forbidden": [], "tag_legend": []}
    notes, offset, modules, labels = [], 0, [], []
    for si, pk in enumerate(a.packs, 1):
        pk = os.path.abspath(pk)
        K = load_pack(pk)
        sp = K["PACK"]
        label = sp.get("scope", os.path.basename(pk)).split("·")[0].strip()
        labels.append(label)
        idmap = {}
        for i, t in enumerate(K["TOPICS"], 1):
            old_n = re.sub(r"\D", "", t["id"])
            idmap[t["id"]] = f"T{offset + i}"
            idmap[f"__num{old_n}"] = str(offset + i)
        for key in ("FORMULAS", "WORKED", "FIGS", "FLOWS", "COMPARISONS"):
            for x in K[key]:
                m = re.match(r"([EGFWC])(\d+)\.(\d+)$", x["id"])
                new_t = idmap.get(f"__num{m.group(2)}") if m else None
                idmap[x["id"]] = f"{m.group(1)}{new_t}.{m.group(3)}" if new_t else f"{x['id']}s{si}"
        idmap = {k: v for k, v in idmap.items() if not k.startswith("__")}
        for k in LISTS:
            if k in ("MODULES",):
                continue
            items = remap(K[k], idmap)
            if k == "SYMBOLS":
                items = [dict(s, where=f"{label}: {s.get('where', '')}") for s in items]
            if k == "RAPID":
                items = [dict(r, q=f"[{label}] {r['q']}") for r in items]
            merged[k] += items
        mid = f"M{si}"
        modules.append({"id": mid, "title": f"{label} · {sp.get('title', '')}", "topics": [idmap[t["id"]] for t in K["TOPICS"]]})
        offset += len(K["TOPICS"])
        for s in sp.get("sources", []):
            P["sources"].append(dict(s, name=f"{label} · {s['name']}"))
        P["gaps"] += [f"{label}: {g}" for g in sp.get("gaps", [])]
        P["asr_forbidden"] += [w for w in sp.get("asr_forbidden", []) if w not in P["asr_forbidden"]]
        P["tag_legend"] += [t for t in sp.get("tag_legend", []) if t not in P["tag_legend"]]
        for f in ("pyq_note", "figure_note", "symbols_remark", "coverage_note"):
            if sp.get(f):
                notes.append((f, f"<b>{label}.</b> {sp[f]}"))
        P.setdefault("course", sp.get("course")); P.setdefault("_first_course", sp.get("course"))
        # figures: re-export under new ids
        for j, fm in enumerate(fig_modules(pk)):
            rel = os.path.relpath(fm, os.path.join(out, "figs"))
            keys = {g["id"]: idmap.get(g["id"], g["id"]) for g in K["FIGS"]}
            with open(os.path.join(out, "figs", f"s{si:02d}_{j}.py"), "w") as fh:
                fh.write(f'"""Generated by merge_unit.py from {os.path.relpath(fm, out)}; do not edit."""\n'
                         "import importlib.util, os\n"
                         f"_p = os.path.join(os.path.dirname(os.path.abspath(__file__)), {rel!r})\n"
                         f"_s = importlib.util.spec_from_file_location('src_s{si:02d}_{j}', _p)\n"
                         "_m = importlib.util.module_from_spec(_s); _s.loader.exec_module(_m)\n"
                         f"_KEYS = {keys!r}\n"
                         "FIGURES = {_KEYS.get(k, k): fn for k, fn in _m.FIGURES.items()}\n")
    # dedupe symbols that are identical apart from the session label
    seen, syms = set(), []
    for s in merged["SYMBOLS"]:
        key = (s["sym"], s["name"], s["meaning"])
        if key not in seen:
            seen.add(key); syms.append(s)
    merged["SYMBOLS"] = syms
    merged["TOP_FORMULAS"] = merged["TOP_FORMULAS"][:24]
    P.pop("_first_course", None)
    P.update({
        "course": a.course or P.get("course"), "unit": a.unit, "title": a.title, "slug": a.slug, "header": a.header,
        "scope": a.scope or f"{a.unit} · all sessions ({labels[0]} – {labels[-1]})",
        "subtitle": f"Unit master: every session of {a.unit} in one document, with one module per session",
        "compiled_from": "Merged from the session packs " + ", ".join(labels) + ". Each module is a complete session pack; "
                         "item numbers are renumbered across the unit, so cross-references point within this document.",
        "how_to_use": "One module per class session, in teaching order. Use the module banners and the contents list to jump "
                      "to a session; the appendices collect every symbol, source and gap of the unit.",
        "pyq_note": "<br>".join(n for f, n in notes if f == "pyq_note"),
        "figure_note": "<br>".join(n for f, n in notes if f == "figure_note"),
        "symbols_remark": "<br>".join(n for f, n in notes if f == "symbols_remark"),
        "coverage_note": "<br>".join(n for f, n in notes if f == "coverage_note"),
    })
    with open(os.path.join(out, "pack.py"), "w") as fh:
        fh.write('"""Generated by merge_unit.py; do not edit (re-run the script)."""\n')
        fh.write("PACK = " + pprint.pformat(P, width=120, sort_dicts=False) + "\n")
        fh.write("MODULES = " + pprint.pformat(modules, width=120, sort_dicts=False) + "\n")
    with open(os.path.join(out, "parts", "merged.py"), "w") as fh:
        fh.write('"""Generated by merge_unit.py; do not edit (re-run the script)."""\n')
        for k in LISTS:
            if k != "MODULES" and merged[k]:
                fh.write(f"{k} = " + pprint.pformat(merged[k], width=120, sort_dicts=False) + "\n")
    gi = os.path.join(out, ".gitignore")
    if not os.path.exists(gi):
        open(gi, "w").write("work/\n__pycache__/\n")
    print(f"merged {len(a.packs)} packs → {out}: {offset} topics, " +
          ", ".join(f"{k}={len(merged[k])}" for k in ("FORMULAS", "WORKED", "FIGS", "FLOWS", "PYQS")))


if __name__ == "__main__":
    main()
